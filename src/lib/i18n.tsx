const dict: Record<Lang, Dict> = { en, hi, ta, te };

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string; }
const LangCtx = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [hydrated, setHydrated] = useState(false);

  useEffect(() => {
    const stored = (typeof window !== "undefined" && (localStorage.getItem("kes_lang") as Lang)) || "en";
    if (stored !== lang) setLangState(stored);
    setHydrated(true);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("kes_lang", l);
  };

  const activeLang = hydrated ? lang : "en";
  const t = (key: string) => dict[activeLang][key] ?? dict.en[key] ?? key;

  return <LangCtx.Provider value={{ lang: activeLang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useT = () => useContext(LangCtx);
